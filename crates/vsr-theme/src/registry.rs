use std::collections::HashMap;
use std::sync::OnceLock;

use serde_json::Value;

use crate::color::{Color, Rgba};

/// `ColorScheme`: the four theme types a default can differ by.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ColorScheme {
    Dark,
    Light,
    HighContrastDark,
    HighContrastLight,
}

impl ColorScheme {
    fn index(self) -> usize {
        match self {
            ColorScheme::Dark => 0,
            ColorScheme::Light => 1,
            ColorScheme::HighContrastDark => 2,
            ColorScheme::HighContrastLight => 3,
        }
    }

    pub fn is_dark(self) -> bool {
        matches!(self, ColorScheme::Dark | ColorScheme::HighContrastDark)
    }

    pub fn is_high_contrast(self) -> bool {
        matches!(self, ColorScheme::HighContrastDark | ColorScheme::HighContrastLight)
    }
}

/// What a colour expression resolves other colour keys through (`IColorTheme`).
pub trait ColorLookup {
    /// The colour of `key` in this theme (theme value or registry default), `None` when unset.
    fn color(&self, key: &str) -> Option<Color>;
    /// Whether the theme itself sets `key` (not just its default): `IColorTheme.defines`.
    fn defines(&self, key: &str) -> bool;
}

/// `ColorValue`.
#[derive(Clone, Debug, PartialEq)]
pub enum ColorValue {
    Color(Color),
    /// Another colour key.
    Ref(String),
    Transform(Box<ColorTransform>),
}

/// `ColorTransform`.
#[derive(Clone, Debug, PartialEq)]
pub enum ColorTransform {
    Darken { value: ColorValue, factor: f64 },
    Lighten { value: ColorValue, factor: f64 },
    Transparent { value: ColorValue, factor: f64 },
    Opacity { value: ColorValue, opacity: f64 },
    Opaque { value: ColorValue, background: ColorValue },
    OneOf(Vec<ColorValue>),
    LessProminent { value: ColorValue, background: ColorValue, factor: f64, transparency: f64 },
    IfDefinedThenElse { key: String, then: ColorValue, otherwise: ColorValue },
    Mix { color: ColorValue, with: ColorValue, ratio: f64 },
}

impl ColorValue {
    /// A string `ColorValue`: `#...` is a colour, anything else a colour key.
    pub fn parse(s: &str) -> Self {
        if s.starts_with('#') { ColorValue::Color(Color::from_hex(s)) } else { ColorValue::Ref(s.to_string()) }
    }

    pub fn transform(t: ColorTransform) -> Self {
        ColorValue::Transform(Box::new(t))
    }
}

/// Recursion guard: a default that refers back to itself resolves to nothing instead of looping.
const MAX_DEPTH: u32 = 64;

/// `resolveColorValue`.
pub fn resolve_color_value(value: &ColorValue, theme: &dyn ColorLookup) -> Option<Color> {
    resolve(value, theme, 0)
}

/// `executeTransform`.
pub fn execute_transform(transform: &ColorTransform, theme: &dyn ColorLookup) -> Option<Color> {
    execute(transform, theme, 0)
}

fn resolve(value: &ColorValue, theme: &dyn ColorLookup, depth: u32) -> Option<Color> {
    if depth > MAX_DEPTH {
        return None;
    }
    match value {
        ColorValue::Color(c) => Some(*c),
        ColorValue::Ref(key) => theme.color(key),
        ColorValue::Transform(t) => execute(t, theme, depth + 1),
    }
}

fn execute(t: &ColorTransform, theme: &dyn ColorLookup, depth: u32) -> Option<Color> {
    use ColorTransform::*;
    let r = |v: &ColorValue| resolve(v, theme, depth);
    match t {
        Darken { value, factor } => r(value).map(|c| c.darken(*factor)),
        Lighten { value, factor } => r(value).map(|c| c.lighten(*factor)),
        Transparent { value, factor } => r(value).map(|c| c.transparent(*factor)),
        Opacity { value, opacity } => r(value).map(|c| Color::from(Rgba::new(f64::from(c.rgba.r), f64::from(c.rgba.g), f64::from(c.rgba.b), *opacity))),
        Mix { color, with, ratio } => {
            let primary = r(color).unwrap_or(Color::TRANSPARENT);
            let other = r(with).unwrap_or(Color::TRANSPARENT);
            Some(primary.mix(&other, *ratio))
        }
        Opaque { value, background } => match r(background) {
            None => r(value),
            Some(bg) => r(value).map(|c| c.make_opaque(&bg)),
        },
        OneOf(values) => values.iter().find_map(r),
        IfDefinedThenElse { key, then, otherwise } => r(if theme.defines(key) { then } else { otherwise }),
        LessProminent { value, background, factor, transparency } => {
            let from = r(value)?;
            match r(background) {
                None => Some(from.transparent(factor * transparency)),
                Some(bg) => Some(if from.is_darker_than(&bg) {
                    Color::lighter_color(&from, &bg, Some(*factor)).transparent(*transparency)
                } else {
                    Color::darker_color(&from, &bg, Some(*factor)).transparent(*transparency)
                }),
            }
        }
    }
}

/// The default of one colour key for each theme type (`ColorDefaults`).
#[derive(Clone, Debug, Default)]
struct Defaults([Option<ColorValue>; 4]);

/// All registered colours and their defaults.
pub struct ColorRegistry {
    defaults: HashMap<String, Defaults>,
}

/// The registry generated from upstream (parsed on first use).
pub fn registry() -> &'static ColorRegistry {
    static REGISTRY: OnceLock<ColorRegistry> = OnceLock::new();
    REGISTRY.get_or_init(|| ColorRegistry::from_json(include_str!("../assets/color-defaults.json")).expect("bundled colour defaults are valid"))
}

impl ColorRegistry {
    fn from_json(text: &str) -> Result<Self, String> {
        let root: Value = serde_json::from_str(text).map_err(|e| e.to_string())?;
        let map = root.as_object().ok_or("colour table must be an object")?;
        let mut defaults = HashMap::with_capacity(map.len());
        for (key, entry) in map {
            let mut d = Defaults::default();
            for (scheme, name) in [
                (ColorScheme::Dark, "dark"),
                (ColorScheme::Light, "light"),
                (ColorScheme::HighContrastDark, "hcDark"),
                (ColorScheme::HighContrastLight, "hcLight"),
            ] {
                d.0[scheme.index()] = entry.get(name).map(parse_value).transpose().map_err(|e| format!("{key}.{name}: {e}"))?.flatten();
            }
            defaults.insert(key.clone(), d);
        }
        Ok(Self { defaults })
    }

    /// Every registered colour key.
    pub fn keys(&self) -> impl Iterator<Item = &str> {
        self.defaults.keys().map(String::as_str)
    }

    pub fn contains(&self, key: &str) -> bool {
        self.defaults.contains_key(key)
    }

    /// The default expression of `key` for `scheme` (`None`: no default).
    pub fn default_value(&self, key: &str, scheme: ColorScheme) -> Option<&ColorValue> {
        self.defaults.get(key)?.0[scheme.index()].as_ref()
    }

    /// `resolveDefaultColor`.
    pub fn resolve_default(&self, key: &str, scheme: ColorScheme, theme: &dyn ColorLookup) -> Option<Color> {
        resolve_color_value(self.default_value(key, scheme)?, theme)
    }
}

fn parse_value(v: &Value) -> Result<Option<ColorValue>, String> {
    let num = |o: &Value, k: &str| o.get(k).and_then(Value::as_f64).ok_or_else(|| format!("missing number '{k}'"));
    let sub = |o: &Value, k: &str| -> Result<ColorValue, String> {
        parse_value(o.get(k).ok_or_else(|| format!("missing '{k}'"))?)?.ok_or_else(|| format!("'{k}' is null"))
    };
    Ok(Some(match v {
        Value::Null => return Ok(None),
        Value::String(s) => ColorValue::Color(Color::from_hex(s)),
        Value::Object(o) => {
            if let Some(r) = o.get("ref") {
                return Ok(Some(ColorValue::Ref(r.as_str().ok_or("ref must be a string")?.to_string())));
            }
            if let Some(Value::Array(a)) = o.get("rgba") {
                let n: Vec<f64> = a.iter().filter_map(Value::as_f64).collect();
                if n.len() < 3 {
                    return Err("rgba needs three or four numbers".into());
                }
                // `new RGBA(r, g, b)`: alpha defaults to 1.
                return Ok(Some(ColorValue::Color(Color::rgba(n[0], n[1], n[2], n.get(3).copied().unwrap_or(1.0)))));
            }
            let op = o.get("op").and_then(Value::as_str).ok_or("unknown colour object")?;
            ColorValue::transform(match op {
                "transparent" => ColorTransform::Transparent { value: sub(v, "v")?, factor: num(v, "f")? },
                "darken" => ColorTransform::Darken { value: sub(v, "v")?, factor: num(v, "f")? },
                "lighten" => ColorTransform::Lighten { value: sub(v, "v")?, factor: num(v, "f")? },
                "opacity" => ColorTransform::Opacity { value: sub(v, "v")?, opacity: num(v, "o")? },
                "opaque" => ColorTransform::Opaque { value: sub(v, "v")?, background: sub(v, "bg")? },
                "mix" => ColorTransform::Mix { color: sub(v, "v")?, with: sub(v, "with")?, ratio: num(v, "ratio")? },
                "oneOf" => ColorTransform::OneOf(
                    o.get("values")
                        .and_then(Value::as_array)
                        .ok_or("oneOf needs values")?
                        .iter()
                        .filter_map(|x| parse_value(x).transpose())
                        .collect::<Result<_, _>>()?,
                ),
                "ifDefined" => ColorTransform::IfDefinedThenElse {
                    key: o.get("key").and_then(Value::as_str).ok_or("ifDefined needs key")?.to_string(),
                    then: sub(v, "then")?,
                    otherwise: sub(v, "else")?,
                },
                "lessProminent" => ColorTransform::LessProminent {
                    value: sub(v, "v")?,
                    background: sub(v, "bg")?,
                    factor: num(v, "f")?,
                    transparency: num(v, "t")?,
                },
                other => return Err(format!("unknown op '{other}'")),
            })
        }
        other => return Err(format!("unexpected {other}")),
    }))
}
